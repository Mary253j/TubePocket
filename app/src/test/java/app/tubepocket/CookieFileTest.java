package app.tubepocket;

import org.junit.Test;
import static org.junit.Assert.*;

public class CookieFileTest {
    @Test public void keepsYoutubeAndHttpOnlyButDropsOtherDomainsAndExpiredRows() {
        CookieFile.Result result = CookieFile.parse("# Netscape HTTP Cookie File\r\n"
                + "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t2000000000\tSID\tFAKE_TEST_SID\r\n"
                + ".youtube.com\tTRUE\t/\tTRUE\t100\tOLD\tFAKE_EXPIRED\r\n"
                + ".google.com\tTRUE\t/\tTRUE\t2000000000\tOTHER\tFAKE_NOT_IMPORTED\r\n", 1000);
        assertEquals(1, result.count); assertTrue(result.text.contains("#HttpOnly_.youtube.com"));
        assertFalse(result.text.contains("FAKE_EXPIRED")); assertFalse(result.text.contains("FAKE_NOT_IMPORTED"));
    }
    @Test public void recognizesBothSessionExpiryConventions() {
        CookieFile.Result result = CookieFile.parse(".youtube.com\tTRUE\t/\tTRUE\t0\tSESSION_A\tFAKE_A\n"
                + "www.youtube.com\tFALSE\t/\tTRUE\t\tSESSION_B\tFAKE_B\n", 2000000000);
        assertEquals(2, result.count);
    }
    @Test public void rejectsMalformedAndSpoofedExportsWithoutEchoingValues() {
        for (String input : new String[]{"[{\"name\":\"SID\",\"value\":\"FAKE_SECRET\"}]", "Cookie: SID=FAKE_SECRET",
                ".youtube.com\tFALSE\t/\tTRUE\t0\tSID\tFAKE_SECRET",
                ".youtube.com\tTRUE\t/\tTRUE\tbroken\tSID\tFAKE_SECRET",
                ".youtube.com.evil.test\tTRUE\t/\tTRUE\t0\tSID\tFAKE_SECRET"}) {
            try { CookieFile.parse(input, 1000); fail("Accepted invalid export"); }
            catch (IllegalArgumentException e) { assertFalse(e.getMessage().contains("FAKE_SECRET")); }
        }
    }
    @Test public void expiredOnlyFilePromptsForFreshExport() {
        try { CookieFile.parse(".youtube.com\tTRUE\t/\tTRUE\t100\tSID\tFAKE_EXPIRED", 1000); fail(); }
        catch (IllegalArgumentException e) { assertTrue(e.getMessage().contains("过期")); }
    }
    @Test public void acceptsCookieEditorMobileNetscapeClipboardFormat() {
        String exported = "# Netscape HTTP Cookie File\n# http://curl.haxx.se/rfc/cookie_spec.html\n# This file was generated by Cookie-Editor"
                + "\n#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t2000000000\tSID\tFAKE_MOBILE_SESSION"
                + "\nwww.youtube.com\tFALSE\t/\tTRUE\t2000000000\tPREF\tf6=40000000";
        CookieFile.Result result = CookieFile.parse(exported, 1900000000);
        assertEquals(2, result.count); assertTrue(result.text.contains("#HttpOnly_.youtube.com"));
    }
}
